CREATE TABLE IF NOT EXISTS public.worm_audit_chain (
   id bigint PRIMARY KEY,
   kind text NOT NULL,
   audit_id bigint NOT NULL,
   detail_ids text NOT NULL,
   prev_hash text NOT NULL,
   link_hash text NOT NULL,
   chained_at timestamptz NOT NULL,
   CHECK (id > 0),
   CHECK (kind IN ('AUDIT', 'LATE_DETAIL')),
   CHECK (prev_hash ~ '^[0-9a-f]{64}$' AND link_hash ~ '^[0-9a-f]{64}$'),
   CHECK (detail_ids = '' OR (detail_ids ~ '^(0|[1-9][0-9]*)(,(0|[1-9][0-9]*))*$' AND cardinality(string_to_array(detail_ids, ',')) <= 250))
);

