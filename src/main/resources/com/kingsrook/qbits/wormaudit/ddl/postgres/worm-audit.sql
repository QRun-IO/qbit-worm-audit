CREATE OR REPLACE FUNCTION public.worm_audit_detail_coverage() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
   -- Serialize even direct SQL appends; the GIN index makes overlap checks indexed.
   PERFORM pg_advisory_xact_lock(86753090421);
   IF NEW.detail_ids <> '' AND (
      EXISTS (SELECT FROM unnest(string_to_array(NEW.detail_ids, ',')) AS d(id) GROUP BY d.id HAVING count(*) > 1)
      OR EXISTS (SELECT FROM public.worm_audit_chain c
         WHERE string_to_array(c.detail_ids, ',') && string_to_array(NEW.detail_ids, ','))) THEN
      RAISE EXCEPTION USING ERRCODE = '23505', MESSAGE = 'worm_audit: audit detail is already covered by the chain';
   END IF;
   RETURN NEW;
END;
$$;

